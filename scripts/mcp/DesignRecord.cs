// Pluto MCP: the design record, one Obsidian note per session for write_design_record. Built from the session folder
// (session.json, notes.jsonl, changes.jsonl, runs.jsonl, runs\rNNN\summary.json), the model basis (describe_basis)
// and the latest hand-check fixture run. Purpose, model basis, assumptions and conditions, decisions and changes,
// analysis and checks, tool verification, open questions, session. Rewriting regenerates every section but keeps the
// text between <!-- pluto:notes KEY --> and <!-- /pluto:notes --> and the properties edited by hand (status, author,
// elements, title unless given again). Never reads or writes the model. C# 5 (see McpServer.cs).
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

public static class DesignRecord
{
    static readonly CultureInfo Inv = CultureInfo.InvariantCulture;
    static readonly string[] Topics = { "geometry", "supports", "materials", "sections", "loads", "analysis", "results" };
    static readonly string[] NoteKeys = { "purpose", "basis", "assumptions", "decisions", "checks", "open" };

    public sealed class Args
    {
        public string Title, Purpose, Author;
        public string[] Elements;
    }

    // The note's id: <model>-<session stamp> (sessions are <work dir>\models\<model>\<stamp>).
    public static string SessionId(string dir)
    {
        string full = Path.GetFullPath(dir).TrimEnd('\\', '/');
        return Path.GetFileName(Path.GetDirectoryName(full)) + "-" + Path.GetFileName(full);
    }

    public static Dictionary<string, object> Write(string dir, string notesDir, Dictionary<string, object> basis, string basisFrom,
        string fixturesFile, Args a)
    {
        notesDir = Path.GetFullPath(notesDir);
        string id = SessionId(dir);
        string file = Path.Combine(notesDir, "Records", id + ".md");
        Dictionary<string, string> kept = new Dictionary<string, string>();
        Dictionary<string, object> props = new Dictionary<string, object>();
        if (File.Exists(file)) { string old = File.ReadAllText(file); kept = NotesBlocks(old); props = Properties(old); }

        Dictionary<string, object> session = ReadJson(Path.Combine(dir, "session.json"));
        List<Dictionary<string, object>> notes = Lines(Path.Combine(dir, "notes.jsonl"));
        List<Dictionary<string, object>> changes = Lines(Path.Combine(dir, "changes.jsonl"));
        List<string> open = new List<string>();
        string model = Path.GetFileName(Json.Str(session, "original") ?? id);

        string purpose;
        if (kept.TryGetValue("purpose", out purpose) && purpose.Trim().Length > 0) { }
        else purpose = a.Purpose ?? "";

        StringBuilder md = new StringBuilder();
        string title = a.Title ?? PropStr(props, "title") ?? "Design record " + model + " " + Stamp(dir);
        string[] elements = a.Elements ?? PropList(props, "elements");
        md.Append("---\n");
        md.Append("title: ").Append(Yaml(title)).Append('\n');
        md.Append("type: design-record\n");
        md.Append("elements:");
        if (elements == null || elements.Length == 0) md.Append(" []\n");
        else { md.Append('\n'); foreach (string e in elements) md.Append("  - ").Append(Yaml(Link(e))).Append('\n'); }
        md.Append("model: ").Append(Yaml(model)).Append('\n');
        md.Append("program: ").Append(Yaml("SAP2000 " + (basis != null ? Json.Str(basis, "version") : Json.Str(session, "sapVersion")))).Append('\n');
        md.Append("session: ").Append(Yaml(id)).Append('\n');
        md.Append("date: ").Append(DateTime.Now.ToString("yyyy-MM-dd", Inv)).Append('\n');
        md.Append("author: ").Append(Yaml(a.Author ?? PropStr(props, "author") ?? "")).Append('\n');
        md.Append("status: ").Append(Yaml(PropStr(props, "status") ?? "draft")).Append('\n');
        md.Append("---\n\n");
        md.Append("# ").Append(title).Append("\n\n");
        md.Append("> [!note] Generated by Pluto's `write_design_record` from the session's own files. Write only between the\n");
        md.Append("> `pluto:notes` markers (kept when the record is rewritten); everything else is regenerated.\n\n");

        md.Append("## Purpose\n\n");
        Block(md, "purpose", purpose);

        md.Append("## Model basis\n\n");
        if (basis == null)
        {
            md.Append("_No model basis: SAP2000 did not hold a checkpoint of this session and none was saved. Open or revert to one, then write the record again._\n\n");
            open.Add("Model basis not read (SAP2000 held no checkpoint of this session).");
        }
        else Basis(md, basis, basisFrom);
        Block(md, "basis", Kept(kept, "basis"));

        Dictionary<string, string> replacedBy = new Dictionary<string, string>();
        foreach (Dictionary<string, object> n in notes) { string s = Json.Str(n, "supersedes"); if (s != null) replacedBy[s] = Json.Str(n, "id"); }
        md.Append("## Assumptions and conditions\n\n");
        int shown = 0;
        foreach (string topic in Topics) shown += NotesByTopic(md, notes, replacedBy, topic, new[] { "assumption", "condition" });
        shown += NotesByTopic(md, notes, replacedBy, null, new[] { "assumption", "condition" });
        if (shown == 0) md.Append("_None logged (log_note kind assumption / condition)._\n\n");
        Block(md, "assumptions", Kept(kept, "assumptions"));

        md.Append("## Decisions and changes\n\n");
        List<Dictionary<string, object>> decisions = notes.FindAll(delegate(Dictionary<string, object> n) { return Json.Str(n, "kind") == "decision"; });
        if (decisions.Count > 0)
        {
            md.Append("### Decisions\n\n");
            foreach (Dictionary<string, object> n in decisions) NoteLine(md, n, replacedBy, notes);
            md.Append('\n');
        }
        md.Append("### Changes to the model\n\n");
        if (changes.Count == 0) md.Append("_No edits: the model was analysed as opened._\n\n");
        else
        {
            md.Append("| Checkpoint | Change | Objects | Reason | When (UTC) |\n|---|---|---|---|---|\n");
            foreach (Dictionary<string, object> c in changes)
                md.Append("| ").Append(Cell(Json.Str(c, "checkpoint"))).Append(" | ").Append(Cell(Json.Str(c, "edit") ?? Json.Str(c, "tool")))
                  .Append(" | ").Append(Cell(Json.Str(c, "changed"))).Append(" | ").Append(Cell(Json.Str(c, "reason") ?? "")).Append(" | ")
                  .Append(Cell(When(Json.Str(c, "utc")))).Append(" |\n");
            md.Append('\n');
        }
        Block(md, "decisions", Kept(kept, "decisions"));

        md.Append("## Analysis and checks\n\n");
        Runs(md, dir, open);
        Block(md, "checks", Kept(kept, "checks"));

        md.Append("## Tool verification\n\n");
        Fixtures(md, fixturesFile, basis != null ? Json.Str(basis, "version") : Json.Str(session, "sapVersion"), open);

        md.Append("## Open questions\n\n");
        foreach (Dictionary<string, object> n in notes)
            if (Json.Str(n, "kind") == "question" && !replacedBy.ContainsKey(Json.Str(n, "id") ?? ""))
                open.Insert(0, Json.Str(n, "text") + " (" + Json.Str(n, "id") + ")");
        if (open.Count == 0) md.Append("_None generated._\n\n");
        else { foreach (string o in open) md.Append("- [ ] ").Append(o).Append('\n'); md.Append('\n'); }
        Block(md, "open", Kept(kept, "open"));

        md.Append("## Session\n\n");
        md.Append("- Folder: `").Append(dir).Append("` ([open](").Append(new Uri(Path.GetFullPath(dir)).AbsoluteUri).Append("))\n");
        md.Append("- Original model: `").Append(Json.Str(session, "original")).Append("`, opened ").Append(When(Json.Str(session, "openedUtc"))).Append(" UTC\n");
        md.Append("- Checkpoints, edit log (`changes.jsonl`), notes (`notes.jsonl`) and run summaries (`runs\\`) stay in the folder.\n");

        Directory.CreateDirectory(Path.GetDirectoryName(file));
        File.WriteAllText(file, md.ToString().Replace("\n", "\r\n"), new UTF8Encoding(false));
        List<string> keptKeys = new List<string>();
        foreach (KeyValuePair<string, string> kv in kept) if (kv.Value.Trim().Length > 0) keptKeys.Add(kv.Key);
        Dictionary<string, object> r = Json.O("file", file, "session", id, "basisFrom", basisFrom, "notes", notes.Count, "changes", changes.Count,
            "openItems", open, "keptNotes", keptKeys);
        if (a.Purpose != null && kept.ContainsKey("purpose") && kept["purpose"].Trim().Length > 0)
            r["purposeKept"] = "the record already has a purpose written by hand; it was kept and purpose was not used";
        return r;
    }

    // ---------------------------------------------------------------- model basis

    static void Basis(StringBuilder md, Dictionary<string, object> b, string from)
    {
        md.Append("Read from **").Append(from).Append("**. Units: ").Append(Json.Str(b, "units")).Append(".\n\n");
        Dictionary<string, object> o = Json.Obj(b, "objects");
        if (o != null)
        {
            List<string> parts = new List<string>();
            foreach (KeyValuePair<string, object> kv in o) if (Convert.ToInt64(kv.Value, Inv) > 0) parts.Add(Convert.ToString(kv.Value, Inv) + " " + kv.Key);
            md.Append("- **Objects:** ").Append(string.Join(", ", parts.ToArray())).Append('\n');
        }
        Dictionary<string, object> s = Json.Obj(b, "supports");
        if (s != null)
        {
            md.Append("- **Supports:** ").Append(Json.Str(s, "restrainedJoints")).Append(" restrained joints");
            Dictionary<string, object> by = Json.Obj(s, "byRestraint");
            if (by != null && by.Count > 0) md.Append(" (").Append(Counts(by)).Append(')');
            if (Num(s, "jointsWithSprings") > 0) md.Append("; ").Append(Json.Str(s, "jointsWithSprings")).Append(" joints on springs");
            if (Num(s, "jointsInConstraints") > 0) md.Append("; ").Append(Json.Str(s, "jointsInConstraints")).Append(" joints in constraints");
            md.Append('\n');
        }
        Dictionary<string, object> rel = Json.Obj(b, "releases");
        if (rel != null)
        {
            md.Append("- **Frame releases:** ");
            Dictionary<string, object> by = Json.Obj(rel, "byRelease");
            md.Append(by == null || by.Count == 0 ? "none" : Counts(by));
            if (Num(rel, "partialFixity") > 0) md.Append("; ").Append(Json.Str(rel, "partialFixity")).Append(" frames with partial fixity");
            md.Append('\n');
        }
        Dictionary<string, object> an = Json.Obj(b, "analysis");
        if (an != null)
        {
            md.Append("- **Active DOFs:** ").Append(Json.Str(an, "activeDof")).Append('\n');
            foreach (Dictionary<string, object> m in Rows(an, "massSources"))
            {
                List<string> from2 = new List<string>();
                if (Json.Bool(m, "fromElements", false)) from2.Add("element self mass");
                if (Json.Bool(m, "fromAddedMasses", false)) from2.Add("added masses");
                if (Json.Bool(m, "fromLoads", false)) from2.Add("loads " + Sum(Rows(m, "loads"), "pattern"));
                md.Append("- **Mass source** ").Append(Json.Str(m, "name")).Append(Json.Bool(m, "default", false) ? " (default)" : "").Append(": ")
                  .Append(from2.Count == 0 ? "nothing" : string.Join(", ", from2.ToArray())).Append('\n');
            }
        }
        md.Append('\n');

        List<Dictionary<string, object>> fs = Used(Rows(b, "frameSections"), "frames"), ar = Used(Rows(b, "areaSections"), "areas"), ln = Used(Rows(b, "linkProperties"), "links");
        // materials the sections in use refer to (all when none is known)
        List<string> inUse = new List<string>();
        foreach (Dictionary<string, object> x in fs) if (Json.Str(x, "material") != null) inUse.Add(Json.Str(x, "material"));
        foreach (Dictionary<string, object> x in ar) if (Json.Str(x, "material") != null) inUse.Add(Json.Str(x, "material"));
        List<Dictionary<string, object>> all = Rows(b, "materials"), mats = all;
        if (inUse.Count > 0) mats = all.FindAll(delegate(Dictionary<string, object> m) { return inUse.Contains(Json.Str(m, "name")); });
        if (mats.Count > 0)
        {
            md.Append("### Materials").Append(mats.Count < all.Count ? " in use" : "").Append("\n\n| Material | Type | E | Weight / volume | Strength |\n|---|---|---|---|---|\n");
            foreach (Dictionary<string, object> m in mats)
            {
                string strength = m.ContainsKey("Fy") ? "Fy " + N(m["Fy"]) + ", Fu " + N(m["Fu"]) : m.ContainsKey("fc") ? "f'c " + N(m["fc"]) : "";
                md.Append("| ").Append(Cell(Json.Str(m, "name"))).Append(" | ").Append(Json.Str(m, "type")).Append(" | ")
                  .Append(m.ContainsKey("E") ? N(m["E"]) : "").Append(" | ").Append(m.ContainsKey("weightPerVolume") ? N(m["weightPerVolume"]) : "")
                  .Append(" | ").Append(strength).Append(" |\n");
            }
            if (mats.Count < all.Count) md.Append("\n_").Append(all.Count - mats.Count).Append(" other defined materials are not used by any section in use._\n");
            md.Append('\n');
        }

        if (fs.Count + ar.Count + ln.Count > 0)
        {
            md.Append("### Sections in use\n\n| Section | Kind | Type | Material / thickness | Objects |\n|---|---|---|---|---|\n");
            foreach (Dictionary<string, object> x in fs)
                md.Append("| ").Append(Cell(Json.Str(x, "name"))).Append(" | frame | ").Append(Json.Str(x, "type")).Append(" | ").Append(Cell(Json.Str(x, "material")))
                  .Append(" | ").Append(Json.Str(x, "frames")).Append(" |\n");
            foreach (Dictionary<string, object> x in ar)
                md.Append("| ").Append(Cell(Json.Str(x, "name"))).Append(" | area | ").Append(Json.Str(x, "shellType") ?? Json.Str(x, "type")).Append(" | ")
                  .Append(Cell(Json.Str(x, "material") ?? "")).Append(x.ContainsKey("membraneThickness") ? ", t " + N(x["membraneThickness"]) : "")
                  .Append(" | ").Append(Json.Str(x, "areas")).Append(" |\n");
            foreach (Dictionary<string, object> x in ln)
                md.Append("| ").Append(Cell(Json.Str(x, "name"))).Append(" | link | ").Append(Json.Str(x, "type")).Append(" |  | ").Append(Json.Str(x, "links")).Append(" |\n");
            md.Append('\n');
        }

        List<Dictionary<string, object>> pats = Rows(b, "loadPatterns");
        if (pats.Count > 0)
        {
            md.Append("### Load patterns\n\n| Pattern | Type | Self weight \u00d7 |\n|---|---|---|\n");
            foreach (Dictionary<string, object> p in pats)
                md.Append("| ").Append(Cell(Json.Str(p, "name"))).Append(" | ").Append(Json.Str(p, "type")).Append(" | ").Append(N(p["selfWeightMultiplier"])).Append(" |\n");
            md.Append('\n');
        }

        List<Dictionary<string, object>> cases = Rows(b, "loadCases");
        if (cases.Count > 0)
        {
            md.Append("### Load cases\n\n| Case | Type | Definition | Status |\n|---|---|---|---|\n");
            foreach (Dictionary<string, object> c in cases)
                md.Append("| ").Append(Cell(Json.Str(c, "name"))).Append(" | ").Append(Json.Str(c, "type")).Append(" | ").Append(Cell(CaseDefinition(c)))
                  .Append(" | ").Append(Json.Str(c, "status")).Append(" |\n");
            md.Append('\n');
        }

        List<Dictionary<string, object>> combos = Rows(b, "combos");
        if (combos.Count > 0)
        {
            md.Append("### Load combinations\n\n| Combination | Type | Items |\n|---|---|---|\n");
            foreach (Dictionary<string, object> c in combos)
            {
                List<string> items = new List<string>();
                foreach (Dictionary<string, object> i in Rows(c, "items")) items.Add(N(i["scale"]) + " " + Json.Str(i, "name"));
                md.Append("| ").Append(Cell(Json.Str(c, "name"))).Append(" | ").Append(Json.Str(c, "type")).Append(" | ").Append(Cell(string.Join(" + ", items.ToArray()))).Append(" |\n");
            }
            md.Append('\n');
        }
        foreach (string k in new[] { "materials", "frameSections", "areaSections", "linkProperties", "loadPatterns", "loadCases", "combos" })
            if (b.ContainsKey(k + "Total")) md.Append("_").Append(k).Append(": the first ").Append(Rows(b, k).Count).Append(" of ").Append(Json.Str(b, k + "Total")).Append(" listed._\n\n");
    }

    static string CaseDefinition(Dictionary<string, object> c)
    {
        List<string> p = new List<string>();
        string type = Json.Str(c, "type");
        List<Dictionary<string, object>> loads = Rows(c, "loads");
        if (type == "ResponseSpectrum")
        {
            foreach (Dictionary<string, object> l in loads) p.Add(Json.Str(l, "direction") + ": " + Json.Str(l, "function") + " \u00d7 " + N(l["scale"]));
            p.Add("modal case " + Json.Str(c, "modalCase"));
            p.Add(Json.Str(c, "modalCombination") + " / " + Json.Str(c, "directionalCombination"));
            if (c.ContainsKey("damping")) p.Add("damping " + N(c["damping"]));
        }
        else if (type == "LinearHistory" && c.ContainsKey("modalCase"))
        {
            foreach (Dictionary<string, object> l in loads) p.Add(Json.Str(l, "name") + " \u00d7 " + N(l["scale"]) + " on " + Json.Str(l, "function"));
            p.Add("modal case " + Json.Str(c, "modalCase"));
            if (c.ContainsKey("steps")) p.Add(Json.Str(c, "steps") + " steps of " + N(c["stepSize"]));
            if (c.ContainsKey("damping")) p.Add("damping " + N(c["damping"]));
        }
        else if (c.ContainsKey("modal"))
        {
            Dictionary<string, object> m = Json.Obj(c, "modal");
            p.Add(Json.Str(m, "method") + ", " + Json.Str(m, "minModes") + " to " + Json.Str(m, "maxModes") + " modes");
        }
        else if (loads.Count > 0)
        {
            List<string> terms = new List<string>();
            foreach (Dictionary<string, object> l in loads) terms.Add(N(l["scale"]) + " " + Json.Str(l, "name"));
            p.Add(string.Join(" + ", terms.ToArray()));
        }
        string init = Json.Str(c, "initialCase");
        if (init != null && init != "None" && init != "(zero)") p.Add("continues from " + init);
        if (c.ContainsKey("geometricNonlinearity")) p.Add("geometry: " + Json.Str(c, "geometricNonlinearity"));
        if (p.Count == 0) return c.ContainsKey("definition") ? "not read" : "";
        return string.Join("; ", p.ToArray());
    }

    // ---------------------------------------------------------------- notes

    static int NotesByTopic(StringBuilder md, List<Dictionary<string, object>> notes, Dictionary<string, string> replacedBy, string topic, string[] kinds)
    {
        List<Dictionary<string, object>> list = notes.FindAll(delegate(Dictionary<string, object> n)
        {
            string t = Json.Str(n, "topic");
            return Array.IndexOf(kinds, Json.Str(n, "kind")) >= 0 && (topic == null ? t == null || Array.IndexOf(Topics, t) < 0 : t == topic);
        });
        if (list.Count == 0) return 0;
        md.Append("### ").Append(topic == null ? "General" : char.ToUpperInvariant(topic[0]) + topic.Substring(1)).Append("\n\n");
        foreach (Dictionary<string, object> n in list) NoteLine(md, n, replacedBy, notes);
        md.Append('\n');
        return list.Count;
    }

    static void NoteLine(StringBuilder md, Dictionary<string, object> n, Dictionary<string, string> replacedBy, List<Dictionary<string, object>> notes)
    {
        string id = Json.Str(n, "id"), by;
        bool old = replacedBy.TryGetValue(id ?? "", out by);
        string kind = Json.Str(n, "kind") ?? "";
        md.Append("- **").Append(kind.Length > 0 ? char.ToUpperInvariant(kind[0]) + kind.Substring(1) : "Note").Append("**: ");
        md.Append(old ? "~~" + Json.Str(n, "text") + "~~ (replaced by " + by + ")" : Json.Str(n, "text"));
        string sup = Json.Str(n, "supersedes");
        Dictionary<string, object> was = sup == null ? null : notes.Find(delegate(Dictionary<string, object> x) { return Json.Str(x, "id") == sup; });
        if (was != null)
            md.Append(" (replaces ").Append(Json.Str(was, "kind")).Append(" ").Append(sup).Append(": \"").Append(Json.Str(was, "text")).Append("\")");
        List<string> meta = new List<string>();
        if (Json.Str(n, "basis") != null) meta.Add("basis: " + Json.Str(n, "basis"));
        List<string> what = new List<string>();
        if (Json.Str(n, "group") != null) what.Add("group " + Json.Str(n, "group"));
        string[] names = Json.Strs(n, "names");
        if (names != null && names.Length > 0) what.Add(names.Length <= 8 ? string.Join(", ", names) : names.Length + " objects");
        if (what.Count > 0) meta.Add("concerns " + string.Join("; ", what.ToArray()));
        string[] els = Json.Strs(n, "elements");
        if (els != null && els.Length > 0) meta.Add(string.Join(", ", Array.ConvertAll(els, Link)));
        meta.Add(id + (Json.Str(n, "checkpoint") != null ? ", " + Json.Str(n, "checkpoint") : ""));
        md.Append(" \u2014 _").Append(string.Join(" \u00b7 ", meta.ToArray())).Append("_\n");
    }

    // ---------------------------------------------------------------- runs and fixtures

    static void Runs(StringBuilder md, string dir, List<string> open)
    {
        string runs = Path.Combine(dir, "runs");
        List<string> summaries = new List<string>();
        if (Directory.Exists(runs))
            foreach (string d in Directory.GetDirectories(runs)) if (File.Exists(Path.Combine(d, "summary.json"))) summaries.Add(d);
        summaries.Sort(StringComparer.OrdinalIgnoreCase);
        if (summaries.Count == 0)
        {
            md.Append("_No analysis run with a summary in this session._\n\n");
            open.Add("No analysis run recorded in this session.");
            return;
        }
        foreach (string d in summaries)
        {
            string cp = Path.GetFileName(d);
            Dictionary<string, object> s = ReadJson(Path.Combine(d, "summary.json"));
            Dictionary<string, object> run = Json.Obj(s, "run");
            md.Append("### Run ").Append(cp).Append(" (").Append(When(Json.Str(s, "utc"))).Append(" UTC)\n\n");
            List<string> done = new List<string>(), other = new List<string>();
            foreach (Dictionary<string, object> c in Rows(run, "cases"))
                (Json.Str(c, "status") == "finished" ? done : other).Add(Json.Str(c, "name") + (Json.Str(c, "status") == "finished" ? "" : " (" + Json.Str(c, "status") + ")"));
            md.Append("- **Cases finished:** ").Append(done.Count == 0 ? "none" : string.Join(", ", done.ToArray())).Append('\n');
            if (other.Count > 0)
            {
                md.Append("- **Not finished:** ").Append(string.Join(", ", other.ToArray())).Append('\n');
                open.Add(cp + ": cases not finished: " + string.Join(", ", other.ToArray()));
            }
            Dictionary<string, object> log = Json.Obj(run, "logMessages");
            if (log != null && Num(log, "total") > 0)
            {
                md.Append("- **Analysis log:** ").Append(Json.Str(log, "total")).Append(" warning / error lines\n");
                int k = 0;
                foreach (string l in Json.Strs(log, "lines") ?? new string[0]) { if (k++ == 5) break; md.Append("  - `").Append(l.Replace("`", "'")).Append("`\n"); }
                open.Add(cp + ": " + Json.Str(log, "total") + " warning / error lines in the analysis log: review them.");
            }
            else md.Append("- **Analysis log:** no warnings\n");
            List<Dictionary<string, object>> eq = Rows(Json.Obj(s, "reactions"), "cases");
            List<string> notChecked = new List<string>();
            foreach (Dictionary<string, object> c in eq)
                if ((Json.Str(c, "check") ?? "").StartsWith("not checked", StringComparison.Ordinal) && !notChecked.Contains(Json.Str(c, "case"))) notChecked.Add(Json.Str(c, "case"));
            eq = eq.FindAll(delegate(Dictionary<string, object> c) { return !(Json.Str(c, "check") ?? "").StartsWith("not checked", StringComparison.Ordinal); });
            if (notChecked.Count > 0)
                md.Append("- **Equilibrium not checked** (envelopes: no single load state): ").Append(string.Join(", ", notChecked.ToArray())).Append('\n');
            if (eq.Count > 0)
            {
                md.Append("\n| Case | Step | Equilibrium (applied + reactions \u2248 0) |\n|---|---|---|\n");
                foreach (Dictionary<string, object> c in eq)
                {
                    string check = Json.Str(c, "check") ?? "";
                    md.Append("| ").Append(Cell(Json.Str(c, "case"))).Append(" | ").Append(Cell(Json.Str(c, "step") ?? "")).Append(" | ").Append(Cell(check)).Append(" |\n");
                    if (check.StartsWith("OFF", StringComparison.Ordinal) || check == "incomplete")
                        open.Add(cp + ": " + Json.Str(c, "case") + " equilibrium " + check + ".");
                }
            }
            md.Append('\n');
        }
    }

    static void Fixtures(StringBuilder md, string file, string version, List<string> open)
    {
        Dictionary<string, object> f = file != null && File.Exists(file) ? ReadJson(file) : null;
        if (f == null)
        {
            md.Append("_No hand-check fixture run recorded (`Test-PlutoMcp.ps1 -Fixtures`)._\n\n");
            open.Add("Tool verification: no hand-check fixture run recorded for SAP2000 " + version + ".");
            return;
        }
        List<Dictionary<string, object>> checks = Rows(f, "checks");
        int pass = checks.FindAll(delegate(Dictionary<string, object> c) { return Json.Bool(c, "pass", false); }).Count;
        md.Append("Hand-check fixtures, SAP2000 ").Append(Json.Str(f, "version")).Append(", ").Append(When(Json.Str(f, "utc"))).Append(" UTC: **")
          .Append(pass).Append(" of ").Append(checks.Count).Append(" pass** (relative tolerance ").Append(N(f.ContainsKey("checks") && checks.Count > 0 ? checks[0]["tolerance"] : null))
          .Append(", units ").Append(Json.Str(f, "units")).Append(").\n\n| Check | Hand value | Hand | SAP2000 | Pass |\n|---|---|---|---|---|\n");
        foreach (Dictionary<string, object> c in checks)
            md.Append("| ").Append(Cell(Json.Str(c, "name"))).Append(" | ").Append(Cell(Json.Str(c, "what") ?? "")).Append(" | ").Append(N(c.ContainsKey("hand") ? c["hand"] : null)).Append(" | ")
              .Append(N(c.ContainsKey("program") ? c["program"] : null)).Append(" | ").Append(Json.Bool(c, "pass", false) ? "yes" : "**no**").Append(" |\n");
        md.Append('\n');
        if (pass < checks.Count) open.Add("Tool verification: " + (checks.Count - pass) + " hand-check fixture(s) fail.");
        if (version != null && Json.Str(f, "version") != version)
            open.Add("Tool verification ran on SAP2000 " + Json.Str(f, "version") + ", the model on " + version + ": run the fixtures again.");
    }

