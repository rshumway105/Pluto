        foreach (string k in new[] { "materials", "frameSections", "areaSections", "linkProperties", "loadPatterns", "loadCases", "combos" })
            if (b.ContainsKey(k + "Total")) md.Append("_").Append(k).Append(": the first ").Append(Rows(b, k).Count).Append(" of ").Append(Json.Str(b, k + "Total")).Append(" listed._\n\n");
    }

    static string CaseDefinition(Dictionary<string, object> c)
    {
        List<string> p = new List<string>();
        string type = Json.Str(c, "type");
        List<Dictionary<string, object>> loads = Rows(c, "loads");
        if (type == "ResponseSpectrum")
        {
            foreach (Dictionary<string, object> l in loads) p.Add(Json.Str(l, "direction") + ": " + Json.Str(l, "function") + " \u00d7 " + N(l["scale"]));
            p.Add("modal case " + Json.Str(c, "modalCase"));
            p.Add(Json.Str(c, "modalCombination") + " / " + Json.Str(c, "directionalCombination"));
            if (c.ContainsKey("damping")) p.Add("damping " + N(c["damping"]));
        }
        else if (type == "LinearHistory" && c.ContainsKey("modalCase"))
        {
            foreach (Dictionary<string, object> l in loads) p.Add(Json.Str(l, "name") + " \u00d7 " + N(l["scale"]) + " on " + Json.Str(l, "function"));
            p.Add("modal case " + Json.Str(c, "modalCase"));
            if (c.ContainsKey("steps")) p.Add(Json.Str(c, "steps") + " steps of " + N(c["stepSize"]));
            if (c.ContainsKey("damping")) p.Add("damping " + N(c["damping"]));
        }
        else if (c.ContainsKey("modal"))
        {
            Dictionary<string, object> m = Json.Obj(c, "modal");
            p.Add(Json.Str(m, "method") + ", " + Json.Str(m, "minModes") + " to " + Json.Str(m, "maxModes") + " modes");
        }
        else if (loads.Count > 0)
        {
            List<string> terms = new List<string>();
            foreach (Dictionary<string, object> l in loads) terms.Add(N(l["scale"]) + " " + Json.Str(l, "name"));
            p.Add(string.Join(" + ", terms.ToArray()));
        }
        string init = Json.Str(c, "initialCase");
        if (init != null && init != "None" && init != "(zero)") p.Add("continues from " + init);
        if (c.ContainsKey("geometricNonlinearity")) p.Add("geometry: " + Json.Str(c, "geometricNonlinearity"));
        if (p.Count == 0) return c.ContainsKey("definition") ? "not read" : "";
        return string.Join("; ", p.ToArray());
    }

