// Pluto MCP: the design record, one Obsidian note per session for write_design_record. Built from the session folder
// (session.json, notes.jsonl, changes.jsonl, runs.jsonl, runs\rNNN\summary.json), the model basis (describe_basis)
// and the latest hand-check fixture run. Purpose, model basis, assumptions and conditions, decisions and changes,
// analysis and checks, tool verification, open questions, session. Rewriting regenerates every section but keeps the
// text between <!-- pluto:notes KEY --> and <!-- /pluto:notes --> and the properties edited by hand (status, author,
// elements, title unless given again). Never reads or writes the model. C# 5 (see McpServer.cs).
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

public static class DesignRecord
{
    static readonly CultureInfo Inv = CultureInfo.InvariantCulture;
    static readonly string[] Topics = { "geometry", "supports", "materials", "sections", "loads", "analysis", "results" };
    static readonly string[] NoteKeys = { "purpose", "basis", "assumptions", "decisions", "checks", "open" };

    public sealed class Args
    {
        public string Title, Purpose, Author;
        public string[] Elements;
    }

    // The note's id: <model>-<session stamp> (sessions are <work dir>\models\<model>\<stamp>).
    public static string SessionId(string dir)
    {
        string full = Path.GetFullPath(dir).TrimEnd('\\', '/');
        return Path.GetFileName(Path.GetDirectoryName(full)) + "-" + Path.GetFileName(full);
    }

    public static Dictionary<string, object> Write(string dir, string notesDir, Dictionary<string, object> basis, string basisFrom,
        string fixturesFile, Args a)
    {
        notesDir = Path.GetFullPath(notesDir);
        string id = SessionId(dir);
        string file = Path.Combine(notesDir, "Records", id + ".md");
        Dictionary<string, string> kept = new Dictionary<string, string>();
        Dictionary<string, object> props = new Dictionary<string, object>();
        if (File.Exists(file)) { string old = File.ReadAllText(file); kept = NotesBlocks(old); props = Properties(old); }

        Dictionary<string, object> session = ReadJson(Path.Combine(dir, "session.json"));
        List<Dictionary<string, object>> notes = Lines(Path.Combine(dir, "notes.jsonl"));
        List<Dictionary<string, object>> changes = Lines(Path.Combine(dir, "changes.jsonl"));
        List<string> open = new List<string>();
        string model = Path.GetFileName(Json.Str(session, "original") ?? id);

        string purpose;
        if (kept.TryGetValue("purpose", out purpose) && purpose.Trim().Length > 0) { }
        else purpose = a.Purpose ?? "";

        StringBuilder md = new StringBuilder();
        string title = a.Title ?? PropStr(props, "title") ?? "Design record " + model + " " + Stamp(dir);
        string[] elements = a.Elements ?? PropList(props, "elements");
        md.Append("---\n");
        md.Append("title: ").Append(Yaml(title)).Append('\n');
        md.Append("type: design-record\n");
        md.Append("elements:");
        if (elements == null || elements.Length == 0) md.Append(" []\n");
        else { md.Append('\n'); foreach (string e in elements) md.Append("  - ").Append(Yaml(Link(e))).Append('\n'); }
        md.Append("model: ").Append(Yaml(model)).Append('\n');
        md.Append("program: ").Append(Yaml("SAP2000 " + (basis != null ? Json.Str(basis, "version") : Json.Str(session, "sapVersion")))).Append('\n');
        md.Append("session: ").Append(Yaml(id)).Append('\n');
        md.Append("date: ").Append(DateTime.Now.ToString("yyyy-MM-dd", Inv)).Append('\n');
        md.Append("author: ").Append(Yaml(a.Author ?? PropStr(props, "author") ?? "")).Append('\n');
        md.Append("status: ").Append(Yaml(PropStr(props, "status") ?? "draft")).Append('\n');
        md.Append("---\n\n");
        md.Append("# ").Append(title).Append("\n\n");
        md.Append("> [!note] Generated by Pluto's `write_design_record` from the session's own files. Write only between the\n");
        md.Append("> `pluto:notes` markers (kept when the record is rewritten); everything else is regenerated.\n\n");

        md.Append("## Purpose\n\n");
        Block(md, "purpose", purpose);

        md.Append("## Model basis\n\n");
        if (basis == null)
        {
            md.Append("_No model basis: SAP2000 did not hold a checkpoint of this session and none was saved. Open or revert to one, then write the record again._\n\n");
            open.Add("Model basis not read (SAP2000 held no checkpoint of this session).");
        }
        else Basis(md, basis, basisFrom);
        Block(md, "basis", Kept(kept, "basis"));

        Dictionary<string, string> replacedBy = new Dictionary<string, string>();
        foreach (Dictionary<string, object> n in notes) { string s = Json.Str(n, "supersedes"); if (s != null) replacedBy[s] = Json.Str(n, "id"); }
        md.Append("## Assumptions and conditions\n\n");
        int shown = 0;
        foreach (string topic in Topics) shown += NotesByTopic(md, notes, replacedBy, topic, new[] { "assumption", "condition" });
        shown += NotesByTopic(md, notes, replacedBy, null, new[] { "assumption", "condition" });
        if (shown == 0) md.Append("_None logged (log_note kind assumption / condition)._\n\n");
        Block(md, "assumptions", Kept(kept, "assumptions"));

        md.Append("## Decisions and changes\n\n");
        List<Dictionary<string, object>> decisions = notes.FindAll(delegate(Dictionary<string, object> n) { return Json.Str(n, "kind") == "decision"; });
        if (decisions.Count > 0)
        {
            md.Append("### Decisions\n\n");
            foreach (Dictionary<string, object> n in decisions) NoteLine(md, n, replacedBy, notes);
            md.Append('\n');
        }
        md.Append("### Changes to the model\n\n");
        if (changes.Count == 0) md.Append("_No edits: the model was analysed as opened._\n\n");
        else
        {
            md.Append("| Checkpoint | Change | Objects | Reason | When (UTC) |\n|---|---|---|---|---|\n");
            foreach (Dictionary<string, object> c in changes)
                md.Append("| ").Append(Cell(Json.Str(c, "checkpoint"))).Append(" | ").Append(Cell(Json.Str(c, "edit") ?? Json.Str(c, "tool")))
                  .Append(" | ").Append(Cell(Json.Str(c, "changed"))).Append(" | ").Append(Cell(Json.Str(c, "reason") ?? "")).Append(" | ")
                  .Append(Cell(When(Json.Str(c, "utc")))).Append(" |\n");
            md.Append('\n');
        }
        Block(md, "decisions", Kept(kept, "decisions"));

        md.Append("## Analysis and checks\n\n");
        Runs(md, dir, open);
        Block(md, "checks", Kept(kept, "checks"));

        md.Append("## Tool verification\n\n");
        Fixtures(md, fixturesFile, basis != null ? Json.Str(basis, "version") : Json.Str(session, "sapVersion"), open);

        md.Append("## Open questions\n\n");
        foreach (Dictionary<string, object> n in notes)
            if (Json.Str(n, "kind") == "question" && !replacedBy.ContainsKey(Json.Str(n, "id") ?? ""))
                open.Insert(0, Json.Str(n, "text") + " (" + Json.Str(n, "id") + ")");
        if (open.Count == 0) md.Append("_None generated._\n\n");
        else { foreach (string o in open) md.Append("- [ ] ").Append(o).Append('\n'); md.Append('\n'); }
        Block(md, "open", Kept(kept, "open"));

        md.Append("## Session\n\n");
        md.Append("- Folder: `").Append(dir).Append("` ([open](").Append(new Uri(Path.GetFullPath(dir)).AbsoluteUri).Append("))\n");
        md.Append("- Original model: `").Append(Json.Str(session, "original")).Append("`, opened ").Append(When(Json.Str(session, "openedUtc"))).Append(" UTC\n");
        md.Append("- Checkpoints, edit log (`changes.jsonl`), notes (`notes.jsonl`) and run summaries (`runs\\`) stay in the folder.\n");

        Directory.CreateDirectory(Path.GetDirectoryName(file));
        File.WriteAllText(file, md.ToString().Replace("\n", "\r\n"), new UTF8Encoding(false));
        List<string> keptKeys = new List<string>();
        foreach (KeyValuePair<string, string> kv in kept) if (kv.Value.Trim().Length > 0) keptKeys.Add(kv.Key);
        Dictionary<string, object> r = Json.O("file", file, "session", id, "basisFrom", basisFrom, "notes", notes.Count, "changes", changes.Count,
            "openItems", open, "keptNotes", keptKeys);
        if (a.Purpose != null && kept.ContainsKey("purpose") && kept["purpose"].Trim().Length > 0)
            r["purposeKept"] = "the record already has a purpose written by hand; it was kept and purpose was not used";
        return r;
    }

    // ---------------------------------------------------------------- element checks (check_elements)

    public sealed class ElementCheck
    {
        public string Element, Group, Quantity, Kind, Limit, Basis;
        public string[] Cases;
        public double? LimitValue;
        public bool Design;
    }

    // The checks an element note asks for: the table under a "Checks" heading (columns Quantity, Kind, Cases, Limit,
    // Basis; an optional Group column overrides the note's `group` property). Kind "design" is SAP2000's steel design
    // ratio over the group's frames (limit 1 unless given).
    public static List<ElementCheck> ReadChecks(string file)
    {
        string text = File.ReadAllText(file);
        Dictionary<string, object> props = Properties(text);
        string element = PropStr(props, "title") ?? Path.GetFileNameWithoutExtension(file), group = PropStr(props, "group");
        List<ElementCheck> r = new List<ElementCheck>();
        string[] lines = text.Replace("\r\n", "\n").Split('\n');
        int i = 0;
        while (i < lines.Length && !Regex.IsMatch(lines[i], @"^#{2,4}\s*Checks\s*$", RegexOptions.IgnoreCase)) i++;
        List<string> cols = null;
        for (i++; i < lines.Length && !lines[i].StartsWith("#", StringComparison.Ordinal); i++)
        {
            string l = lines[i].Trim();
            if (!l.StartsWith("|", StringComparison.Ordinal)) { if (cols != null) break; continue; }
            List<string> cells = Cells(l);
            if (cols == null) { cols = cells.ConvertAll(delegate(string h) { return h.ToLowerInvariant(); }); continue; }
            if (cells.TrueForAll(delegate(string s) { return Regex.IsMatch(s, @"^:?-*:?$"); })) continue;   // the separator row
            Func<string, string> at = delegate(string name) { int k = cols.IndexOf(name); return k >= 0 && k < cells.Count ? cells[k] : ""; };
            ElementCheck c = new ElementCheck();
            c.Element = element; c.Quantity = at("quantity"); c.Kind = at("kind").ToLowerInvariant(); c.Limit = at("limit"); c.Basis = at("basis");
            c.Group = at("group").Length > 0 ? at("group") : group;
            if (c.Quantity.Length == 0 && c.Kind.Length == 0) continue;
            c.Design = c.Kind == "design" || c.Kind == "steel design";
            string cs = at("cases");
            c.Cases = cs.Length == 0 ? null : Array.ConvertAll(cs.Split(','), delegate(string s) { return s.Trim(); });
            Match m = Regex.Match(c.Limit.Replace(",", ""), @"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?");
            if (m.Success) c.LimitValue = double.Parse(m.Value, NumberStyles.Float, Inv);
            else if (c.Design) c.LimitValue = 1;
            r.Add(c);
        }
        return r;
    }

    static List<string> Cells(string row)
    {
        string s = row.Trim();
        if (s.StartsWith("|", StringComparison.Ordinal)) s = s.Substring(1);
        if (s.EndsWith("|", StringComparison.Ordinal) && !s.EndsWith("\\|", StringComparison.Ordinal)) s = s.Substring(0, s.Length - 1);
        List<string> r = new List<string>();
        foreach (string c in Regex.Split(s, @"(?<!\\)\|")) r.Add(c.Replace("\\|", "|").Trim());
        return r;
    }

    // The governing checks saved by check_elements for one run checkpoint (checks-rNNN.json), as a table.
    static void Checks(StringBuilder md, string file, string cp, List<string> open)
    {
        Dictionary<string, object> f = ReadJson(file);
        List<Dictionary<string, object>> rows = Rows(f, "rows");
        if (rows.Count == 0) return;
        md.Append("\n**Governing checks** (check_elements, ").Append(When(Json.Str(f, "utc"))).Append(" UTC, units ").Append(Json.Str(f, "units")).Append(")\n\n")
          .Append("| Element | Check | Governing | Value | Case | Limit | Ratio |\n|---|---|---|---|---|---|---|\n");
        foreach (Dictionary<string, object> r in rows)
        {
            string check = Json.Str(r, "check") + (Json.Str(r, "kind") != null && Json.Str(r, "kind") != "design" ? " (" + Json.Str(r, "kind") + ")" : "");
            string gov = Json.Str(r, "object") == null ? "_" + (Json.Str(r, "note") ?? "no result") + "_" :
                Json.Str(r, "object") + (string.IsNullOrEmpty(Json.Str(r, "at")) ? "" : " at " + N(r["at"]));
            string ratio = r.ContainsKey("ratio") && r["ratio"] != null ? N(r["ratio"]) : "";
            bool over = r.ContainsKey("ratio") && r["ratio"] != null && Num(r, "ratio") > 1;
            md.Append("| ").Append(Cell(Json.Str(r, "element"))).Append(" | ").Append(Cell(check)).Append(" | ").Append(Cell(gov)).Append(" | ")
              .Append(r.ContainsKey("value") ? N(r["value"]) : "").Append(" | ").Append(Cell(Json.Str(r, "case") ?? "")).Append(" | ")
              .Append(Cell(Json.Str(r, "limit") ?? "")).Append(" | ").Append(over ? "**" + ratio + "**" : ratio).Append(" |\n");
            if (over) open.Add(cp + ": " + Json.Str(r, "element") + " " + Json.Str(r, "check") + " ratio " + ratio + " exceeds 1.");
            else if (Json.Str(r, "object") == null) open.Add(cp + ": " + Json.Str(r, "element") + " " + Json.Str(r, "check") + ": " + (Json.Str(r, "note") ?? "no result") + ".");
        }
    }

    // ---------------------------------------------------------------- BOD element note (draft)

    // A first draft of a basis-of-design element note, <notes dir>\Elements\<element>.md, in the shape of
    // vault/_meta/templates/bod-element.md: the model's load patterns and combinations, the group's objects and supports,
    // the assumptions and conditions logged for this element, the model and its design record. Never overwrites: once
    // the note exists it is the engineer's. basis / group: JSON-parsed describe_basis / SapRead.GroupSummary (group may be null).
    public static Dictionary<string, object> DraftElement(string element, string notesDir, Dictionary<string, object> basis,
        Dictionary<string, object> group, string sessionDir)
    {
        notesDir = Path.GetFullPath(notesDir);
        if (element.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || element.Contains("[") || element.Contains("]") || element.Contains("|") || element.Contains("#"))
            throw new ToolError("element '" + element + "' cannot be a note name (no \\ / : * ? \" < > | [ ] #)");
        string file = Path.Combine(notesDir, "Elements", element + ".md");
        if (File.Exists(file)) throw new ToolError(file + " exists: an element note is written by hand once drafted, so Pluto does not overwrite it");
        string model = basis == null ? null : Path.GetFileName(Json.Str(basis, "model"));
        Dictionary<string, object> session = sessionDir == null ? null : ReadJson(Path.Combine(sessionDir, "session.json"));
        string original = session == null ? model : Path.GetFileName(Json.Str(session, "original"));

        StringBuilder md = new StringBuilder();
        md.Append("---\n");
        md.Append("title: ").Append(Yaml(element)).Append('\n');
        md.Append("type: bod-element\n");
        md.Append("status: draft\n");
        md.Append("created: ").Append(DateTime.Now.ToString("yyyy-MM-dd", Inv)).Append('\n');
        if (original != null) md.Append("model: ").Append(Yaml(original)).Append('\n');
        if (group != null) md.Append("group: ").Append(Yaml(Json.Str(group, "group"))).Append('\n');
        md.Append("---\n\n# ").Append(element).Append("\n\n");
        md.Append("> [!info] Basis-of-design element note, drafted by Pluto's `draft_bod_element` from ").Append(original ?? "the model")
          .Append(" on ").Append(DateTime.Now.ToString("yyyy-MM-dd", Inv)).Append(". Pluto does not edit it again: correct and complete it by\n")
          .Append("> hand. The design records that support it link here through their `elements` property and are listed at the end.\n\n");

        md.Append("## Description\n\nWhat the element is, where it is, and what it does.\n\n");
        if (group != null)
        {
            md.Append("In the model it is group **").Append(Json.Str(group, "group")).Append("**:\n\n");
            Dictionary<string, object> objs = Json.Obj(group, "objects");
            if (objs != null)
                foreach (KeyValuePair<string, object> kv in objs)
                {
                    Dictionary<string, object> d = kv.Value as Dictionary<string, object>;
                    if (d == null || Num(d, "count") == 0) continue;
                    md.Append("- ").Append(Json.Str(d, "count")).Append(' ').Append(kv.Key).Append('s');
                    Dictionary<string, object> by = Json.Obj(d, "byProperty");
                    if (by != null && by.Count > 0) md.Append(" (").Append(Counts(by)).Append(')');
                    Dictionary<string, object> ext = Json.Obj(d, "extent");
                    if (ext != null) md.Append(", from ").Append(Xyz(ext["min"])).Append(" to ").Append(Xyz(ext["max"]));
                    md.Append('\n');
                }
            Dictionary<string, object> sup = Json.Obj(group, "supports");
            if (sup != null && Num(sup, "restrainedJoints") > 0)
                md.Append("- ").Append(Json.Str(sup, "restrainedJoints")).Append(" restrained joints (").Append(Counts(Json.Obj(sup, "byRestraint"))).Append(")\n");
            if (basis != null) md.Append("\nCoordinates in ").Append(Json.Str(basis, "units")).Append(", global.\n");
            md.Append('\n');
        }

        md.Append("## Design criteria\n\n- Codes and editions:\n- Limit states and acceptance criteria (stress, deflection, drift):\n- Category / importance factors:\n\n");
        md.Append("### Checks\n\nWhat `check_elements` reports for this element: the governing result over the group (and its ratio to the limit,\n")
          .Append("when one is given). Kind: joint, reaction, frame, area, area_stress, link, or design (SAP2000 steel design ratio).\n")
          .Append("Cases: blank for all, or names / wildcards separated by commas. Limit in the model's units.\n\n")
          .Append("| Quantity | Kind | Cases | Limit | Basis |\n|---|---|---|---|---|\n");
        foreach (string[] row in SuggestedChecks(group, basis)) md.Append("| ").Append(string.Join(" | ", row)).Append(" |\n");
        md.Append('\n');

        md.Append("## Loads\n\n");
        List<Dictionary<string, object>> pats = Rows(basis, "loadPatterns");
        if (pats.Count == 0) md.Append("| Load | Value | Basis |\n|---|---|---|\n|  |  |  |\n\n");
        else
        {
            md.Append("Load patterns in the model (fill in the values and their basis):\n\n| Load pattern | Type | Value | Basis |\n|---|---|---|---|\n");
            foreach (Dictionary<string, object> p in pats)
                md.Append("| ").Append(Cell(Json.Str(p, "name"))).Append(" | ").Append(Json.Str(p, "type"))
                  .Append(Num(p, "selfWeightMultiplier") != 0 ? ", self weight \u00d7 " + N(p["selfWeightMultiplier"]) : "").Append(" |  |  |\n");
            md.Append('\n');
        }
        List<Dictionary<string, object>> combos = Rows(basis, "combos");
        md.Append("Combinations used:");
        if (combos.Count == 0) md.Append("\n\n");
        else
        {
            md.Append("\n\n");
            foreach (Dictionary<string, object> c in combos)
            {
                List<string> items = new List<string>();
                foreach (Dictionary<string, object> i in Rows(c, "items")) items.Add(N(i["scale"]) + " " + Json.Str(i, "name"));
                md.Append("- ").Append(Json.Str(c, "name")).Append(" (").Append(Json.Str(c, "type")).Append("): ").Append(string.Join(" + ", items.ToArray())).Append('\n');
            }
            md.Append('\n');
        }

        md.Append("## Conditions and assumptions\n\nWhat holds for this element whatever the model: supports, existing structure, site and supplied data, each with its\nbasis. Assumptions tied to one model are in that model's design records.\n\n");
        List<Dictionary<string, object>> notes = sessionDir == null ? new List<Dictionary<string, object>>() : Lines(Path.Combine(sessionDir, "notes.jsonl"));
        HashSet<string> replaced = new HashSet<string>();
        foreach (Dictionary<string, object> n in notes) if (Json.Str(n, "supersedes") != null) replaced.Add(Json.Str(n, "supersedes"));
        List<Dictionary<string, object>> mine = notes.FindAll(delegate(Dictionary<string, object> n)
        {
            string k = Json.Str(n, "kind");
            string[] els = Json.Strs(n, "elements");
            return (k == "assumption" || k == "condition") && !replaced.Contains(Json.Str(n, "id") ?? "") && els != null && Array.IndexOf(els, element) >= 0;
        });
        if (mine.Count > 0)
        {
            md.Append("Logged for this element in the Pluto session (keep what holds beyond this model):\n\n");
            foreach (Dictionary<string, object> n in mine)
            {
                string k = Json.Str(n, "kind");
                md.Append("- **").Append(char.ToUpperInvariant(k[0]) + k.Substring(1)).Append("**: ").Append(Json.Str(n, "text"));
                if (Json.Str(n, "basis") != null) md.Append(" \u2014 _basis: ").Append(Json.Str(n, "basis")).Append('_');
                md.Append('\n');
            }
            md.Append('\n');
        }

        md.Append("## Models\n\n");
        string record = sessionDir == null ? null : SessionId(sessionDir);
        bool recordExists = record != null && File.Exists(Path.Combine(notesDir, "Records", record + ".md"));
        md.Append("- ").Append(original != null ? "`" + original + "`" : "").Append(recordExists ? " \u2014 design record [[" + record + "]]" : "").Append('\n');
        md.Append('\n');

        md.Append("## Governing checks\n\n| Check | Governing case | Demand | Capacity | Ratio | Record |\n|---|---|---|---|---|---|\n|  |  |  |  |  |  |\n\n");
        md.Append("## Design records\n\n```base\nfilters:\n  and:\n    - 'type == \"design-record\"'\n    - 'file.hasLink(this.file)'\nviews:\n")
          .Append("  - type: table\n    name: Records for this element\n    order:\n      - file.name\n      - model\n      - date\n      - author\n      - status\n```\n");

        Directory.CreateDirectory(Path.GetDirectoryName(file));
        File.WriteAllText(file, md.ToString().Replace("\n", "\r\n"), new UTF8Encoding(false));
        return Json.O("file", file, "element", element, "model", original, "group", group == null ? null : Json.Str(group, "group"),
            "loadPatterns", pats.Count, "combos", combos.Count, "notes", mine.Count, "record", recordExists ? record : null,
            "note", "a draft: the engineer completes it by hand (criteria, load values and basis, governing checks); Pluto never overwrites it." +
                (recordExists || record == null ? "" : " write_design_record with elements [\"" + element + "\"] links this session's record to it."));
    }

    // Checks to start from, by what the group holds: shells -> von Mises stress top / bottom; frames -> P, V2, M3 (and the
    // steel design ratio when a frame section is steel); joints only -> displacement. Limits and basis left blank.
    static List<string[]> SuggestedChecks(Dictionary<string, object> group, Dictionary<string, object> basis)
    {
        List<string[]> r = new List<string[]>();
        Dictionary<string, object> objs = group == null ? null : Json.Obj(group, "objects");
        Func<string, Dictionary<string, object>> kind = delegate(string k) { Dictionary<string, object> d = Json.Obj(objs, k); return d != null && Num(d, "count") > 0 ? d : null; };
        if (objs != null && kind("area") != null)
        {
            r.Add(new[] { "SVMTop", "area_stress", "", "", "" });
            r.Add(new[] { "SVMBot", "area_stress", "", "", "" });
        }
        Dictionary<string, object> frames = objs == null ? null : kind("frame");
        if (frames != null)
        {
            r.Add(new[] { "P", "frame", "", "", "" });
            r.Add(new[] { "V2", "frame", "", "", "" });
            r.Add(new[] { "M3", "frame", "", "", "" });
            Dictionary<string, object> used = Json.Obj(frames, "byProperty");
            HashSet<string> steel = new HashSet<string>();
            foreach (Dictionary<string, object> m in Rows(basis, "materials")) if (Json.Str(m, "type") == "Steel") steel.Add(Json.Str(m, "name"));
            bool anySteel = false;
            foreach (Dictionary<string, object> s in Rows(basis, "frameSections"))
                if (used != null && used.ContainsKey(Json.Str(s, "name") ?? "") && steel.Contains(Json.Str(s, "material") ?? "")) anySteel = true;
            if (anySteel) r.Add(new[] { "steel design ratio", "design", "", "1.0", "" });
        }
        if (objs != null && r.Count == 0 && kind("joint") != null) r.Add(new[] { "U", "joint", "", "", "" });
        if (r.Count == 0) r.Add(new[] { "", "", "", "", "" });
        return r;
    }

    static string Xyz(object v)
    {
        System.Collections.IEnumerable seq = v as System.Collections.IEnumerable;
        if (seq == null) return "?";
        List<string> p = new List<string>();
        foreach (object o in seq) p.Add(N(o));
        return "(" + string.Join(", ", p.ToArray()) + ")";
    }

    // ---------------------------------------------------------------- model basis

    static void Basis(StringBuilder md, Dictionary<string, object> b, string from)
    {
        md.Append("Read from **").Append(from).Append("**. Units: ").Append(Json.Str(b, "units")).Append(".\n\n");
        Dictionary<string, object> o = Json.Obj(b, "objects");
        if (o != null)
        {
            List<string> parts = new List<string>();
            foreach (KeyValuePair<string, object> kv in o) if (Convert.ToInt64(kv.Value, Inv) > 0) parts.Add(Convert.ToString(kv.Value, Inv) + " " + kv.Key);
            md.Append("- **Objects:** ").Append(string.Join(", ", parts.ToArray())).Append('\n');
        }
        Dictionary<string, object> s = Json.Obj(b, "supports");
        if (s != null)
        {
            md.Append("- **Supports:** ").Append(Json.Str(s, "restrainedJoints")).Append(" restrained joints");
            Dictionary<string, object> by = Json.Obj(s, "byRestraint");
            if (by != null && by.Count > 0) md.Append(" (").Append(Counts(by)).Append(')');
            if (Num(s, "jointsWithSprings") > 0) md.Append("; ").Append(Json.Str(s, "jointsWithSprings")).Append(" joints on springs");
            if (Num(s, "jointsInConstraints") > 0) md.Append("; ").Append(Json.Str(s, "jointsInConstraints")).Append(" joints in constraints");
            md.Append('\n');
        }
        Dictionary<string, object> rel = Json.Obj(b, "releases");
        if (rel != null)
        {
            md.Append("- **Frame releases:** ");
            Dictionary<string, object> by = Json.Obj(rel, "byRelease");
            md.Append(by == null || by.Count == 0 ? "none" : Counts(by));
            if (Num(rel, "partialFixity") > 0) md.Append("; ").Append(Json.Str(rel, "partialFixity")).Append(" frames with partial fixity");
            md.Append('\n');
        }
        Dictionary<string, object> an = Json.Obj(b, "analysis");
        if (an != null)
        {
            md.Append("- **Active DOFs:** ").Append(Json.Str(an, "activeDof")).Append('\n');
            foreach (Dictionary<string, object> m in Rows(an, "massSources"))
            {
                List<string> from2 = new List<string>();
                if (Json.Bool(m, "fromElements", false)) from2.Add("element self mass");
                if (Json.Bool(m, "fromAddedMasses", false)) from2.Add("added masses");
                if (Json.Bool(m, "fromLoads", false)) from2.Add("loads " + Sum(Rows(m, "loads"), "pattern"));
                md.Append("- **Mass source** ").Append(Json.Str(m, "name")).Append(Json.Bool(m, "default", false) ? " (default)" : "").Append(": ")
                  .Append(from2.Count == 0 ? "nothing" : string.Join(", ", from2.ToArray())).Append('\n');
            }
        }
        md.Append('\n');

        List<Dictionary<string, object>> fs = Used(Rows(b, "frameSections"), "frames"), ar = Used(Rows(b, "areaSections"), "areas"), ln = Used(Rows(b, "linkProperties"), "links");
        // materials the sections in use refer to (all when none is known)
        List<string> inUse = new List<string>();
        foreach (Dictionary<string, object> x in fs) if (Json.Str(x, "material") != null) inUse.Add(Json.Str(x, "material"));
        foreach (Dictionary<string, object> x in ar) if (Json.Str(x, "material") != null) inUse.Add(Json.Str(x, "material"));
        List<Dictionary<string, object>> all = Rows(b, "materials"), mats = all;
        if (inUse.Count > 0) mats = all.FindAll(delegate(Dictionary<string, object> m) { return inUse.Contains(Json.Str(m, "name")); });
        if (mats.Count > 0)
        {
            md.Append("### Materials").Append(mats.Count < all.Count ? " in use" : "").Append("\n\n| Material | Type | E | Weight / volume | Strength |\n|---|---|---|---|---|\n");
            foreach (Dictionary<string, object> m in mats)
            {
                string strength = m.ContainsKey("Fy") ? "Fy " + N(m["Fy"]) + ", Fu " + N(m["Fu"]) : m.ContainsKey("fc") ? "f'c " + N(m["fc"]) : "";
                md.Append("| ").Append(Cell(Json.Str(m, "name"))).Append(" | ").Append(Json.Str(m, "type")).Append(" | ")
                  .Append(m.ContainsKey("E") ? N(m["E"]) : "").Append(" | ").Append(m.ContainsKey("weightPerVolume") ? N(m["weightPerVolume"]) : "")
                  .Append(" | ").Append(strength).Append(" |\n");
            }
            if (mats.Count < all.Count) md.Append("\n_").Append(all.Count - mats.Count).Append(" other defined materials are not used by any section in use._\n");
            md.Append('\n');
        }

        if (fs.Count + ar.Count + ln.Count > 0)
        {
            md.Append("### Sections in use\n\n| Section | Kind | Type | Material / thickness | Objects |\n|---|---|---|---|---|\n");
            foreach (Dictionary<string, object> x in fs)
                md.Append("| ").Append(Cell(Json.Str(x, "name"))).Append(" | frame | ").Append(Json.Str(x, "type")).Append(" | ").Append(Cell(Json.Str(x, "material")))
