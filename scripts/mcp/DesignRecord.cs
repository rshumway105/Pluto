    static void Block(StringBuilder md, string key, string text)
    {
        md.Append("<!-- pluto:notes ").Append(key).Append(" -->\n");
        string t = (text ?? "").Trim('\r', '\n');
        if (t.Length > 0) md.Append(t.Replace("\r\n", "\n")).Append('\n');
        md.Append("<!-- /pluto:notes -->\n\n");
    }

    static string Kept(Dictionary<string, string> kept, string key) { string v; return kept.TryGetValue(key, out v) ? v : ""; }

    static Dictionary<string, string> NotesBlocks(string text)
    {
        Dictionary<string, string> r = new Dictionary<string, string>();
        foreach (Match m in Regex.Matches(text, @"<!-- pluto:notes (\w+) -->\r?\n(.*?)<!-- /pluto:notes -->", RegexOptions.Singleline))
            if (Array.IndexOf(NoteKeys, m.Groups[1].Value) >= 0) r[m.Groups[1].Value] = m.Groups[2].Value;
        return r;
    }

    // The frontmatter as key -> string or string[] (block lists only), enough for the properties this note writes.
    static Dictionary<string, object> Properties(string text)
    {
        Dictionary<string, object> r = new Dictionary<string, object>();
        string[] lines = text.Replace("\r\n", "\n").Split('\n');
        if (lines.Length == 0 || lines[0].Trim() != "---") return r;
        string listKey = null; List<string> list = null;
        for (int i = 1; i < lines.Length && lines[i].Trim() != "---"; i++)
        {
            string l = lines[i];
            if (listKey != null && l.TrimStart().StartsWith("- ", StringComparison.Ordinal)) { list.Add(Unyaml(l.TrimStart().Substring(2))); continue; }
            if (listKey != null) { r[listKey] = list.ToArray(); listKey = null; }
            int c = l.IndexOf(':');
            if (c <= 0) continue;
            string k = l.Substring(0, c).Trim(), v = l.Substring(c + 1).Trim();
            if (v.Length == 0) { listKey = k; list = new List<string>(); }
            else if (v == "[]") r[k] = new string[0];
            else r[k] = Unyaml(v);
        }
        if (listKey != null) r[listKey] = list.ToArray();
        return r;
    }

    static string PropStr(Dictionary<string, object> p, string k) { object v; return p.TryGetValue(k, out v) && v is string && ((string)v).Length > 0 ? (string)v : null; }

    static string[] PropList(Dictionary<string, object> p, string k)
    {
        object v;
        if (!p.TryGetValue(k, out v) || !(v is string[])) return null;
        return Array.ConvertAll((string[])v, delegate(string s) { return Regex.Replace(s, @"^\[\[(.*?)(\|.*)?\]\]$", "$1"); });
    }

    // ---------------------------------------------------------------- helpers

    static string Link(string element) { return element.StartsWith("[[", StringComparison.Ordinal) ? element : "[[" + element + "]]"; }

    static string Yaml(string s) { return "\"" + (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"") + "\""; }

    static string Unyaml(string s)
    {
        s = s.Trim();
        if (s.Length >= 2 && s[0] == '"' && s[s.Length - 1] == '"') return s.Substring(1, s.Length - 2).Replace("\\\"", "\"").Replace("\\\\", "\\");
        if (s.Length >= 2 && s[0] == '\'' && s[s.Length - 1] == '\'') return s.Substring(1, s.Length - 2).Replace("''", "'");
        return s;
    }

    static string Cell(string s) { return (s ?? "").Replace("|", "\\|").Replace("\r", " ").Replace("\n", " "); }

    static string Stamp(string dir) { return Path.GetFileName(Path.GetFullPath(dir).TrimEnd('\\', '/')); }

    static string When(string utc) { return utc == null ? "?" : utc.Replace("T", " ").TrimEnd('Z'); }

    static double Num(Dictionary<string, object> d, string k)
    {
        object v;
        if (d == null || !d.TryGetValue(k, out v) || v == null) return 0;
        double x;
        return double.TryParse(Convert.ToString(v, Inv), NumberStyles.Float, Inv, out x) ? x : 0;
    }

    static string N(object v)
    {
        if (v == null) return "";
        double x;
        if (!double.TryParse(Convert.ToString(v, Inv), NumberStyles.Float, Inv, out x)) return Convert.ToString(v, Inv);
        if (x == 0) return "0";
        double r = double.Parse(x.ToString("G6", Inv), NumberStyles.Float, Inv);   // 6 significant digits
        return Math.Abs(r) >= 1e-4 && Math.Abs(r) < 1e12 ? r.ToString("#,##0.##########", Inv) : r.ToString("G6", Inv);
    }

    static string Counts(Dictionary<string, object> by)
    {
        List<string> p = new List<string>();
        foreach (KeyValuePair<string, object> kv in by) p.Add(kv.Key + " \u00d7 " + Convert.ToString(kv.Value, Inv));
        return string.Join("; ", p.ToArray());
    }

    static string Sum(List<Dictionary<string, object>> loads, string key)
    {
        List<string> p = new List<string>();
        foreach (Dictionary<string, object> l in loads) p.Add(N(l["scale"]) + " " + Json.Str(l, key));
        return string.Join(" + ", p.ToArray());
    }

    static List<Dictionary<string, object>> Used(List<Dictionary<string, object>> rows, string countKey)
    {
        return rows.FindAll(delegate(Dictionary<string, object> r) { return Num(r, countKey) > 0; });
    }

    static List<Dictionary<string, object>> Rows(Dictionary<string, object> d, string key)
    {
        List<Dictionary<string, object>> r = new List<Dictionary<string, object>>();
        object v;
        if (d == null || !d.TryGetValue(key, out v) || v == null) return r;
        System.Collections.IEnumerable seq = v as System.Collections.IEnumerable;
        if (seq == null || v is string) return r;
        foreach (object o in seq) { Dictionary<string, object> x = o as Dictionary<string, object>; if (x != null) r.Add(x); }
        return r;
    }

    static Dictionary<string, object> ReadJson(string file)
    {
        return File.Exists(file) ? Json.Parse(File.ReadAllText(file)) as Dictionary<string, object> : null;
    }

    static List<Dictionary<string, object>> Lines(string file)
    {
        List<Dictionary<string, object>> r = new List<Dictionary<string, object>>();
        if (!File.Exists(file)) return r;
        foreach (string l in File.ReadAllLines(file))
        {
            if (l.Trim().Length == 0) continue;
            Dictionary<string, object> d = Json.Parse(l) as Dictionary<string, object>;
            if (d != null) r.Add(d);
        }
        return r;
    }
